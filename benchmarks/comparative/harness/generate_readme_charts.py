ROOT = Path(__file__).resolve().parents[3]
DEFAULT_RUN_DIR = ROOT / "benchmarks/comparative/results/2026-07-08-manual-all"
DEFAULT_OUT_DIR = ROOT / "docs/assets"

REVOQ = "#0f766e"
AERON = "#2563eb"
CHRONICLE = "#a16207"
INK = "#172033"
MUTED = "#64748b"
GRID = "#d8dee8"
PAPER = "#ffffff"
PANEL = "#f8fafc"


def esc(value: Any) -> str:
    return html.escape(str(value), quote=True)


def tag(name: str, attrs: dict[str, Any] | None = None, body: str = "") -> str:
    attrs = attrs or {}
    joined = "".join(f' {k}="{esc(v)}"' for k, v in attrs.items())
    if body:
        return f"<{name}{joined}>{body}</{name}>"
    return f"<{name}{joined}/>"


def text(x: float, y: float, value: Any, **attrs: Any) -> str:
    base = {"x": round(x, 2), "y": round(y, 2)}
    base.update(attrs)
    return tag("text", base, esc(value))


def rect(x: float, y: float, w: float, h: float, **attrs: Any) -> str:
    base = {
        "x": round(x, 2),
        "y": round(y, 2),
        "width": round(w, 2),
        "height": round(h, 2),
    }
    base.update(attrs)
    return tag("rect", base)


def line(x1: float, y1: float, x2: float, y2: float, **attrs: Any) -> str:
    base = {
        "x1": round(x1, 2),
        "y1": round(y1, 2),
        "x2": round(x2, 2),
        "y2": round(y2, 2),
    }
    base.update(attrs)
    return tag("line", base)


def svg_doc(width: int, height: int, title: str, desc: str,
            body: list[str]) -> str:
    style = """
    text { font-family: Inter, ui-sans-serif, system-ui, -apple-system, Segoe UI, sans-serif; }
    .title { font-size: 24px; font-weight: 700; fill: #172033; }
    .subtitle { font-size: 14px; fill: #64748b; }
    .axis { font-size: 12px; fill: #64748b; }
    .label { font-size: 13px; fill: #172033; }
    .small { font-size: 11px; fill: #64748b; }
    .value { font-size: 11px; font-weight: 700; fill: #172033; }
    .legend { font-size: 13px; fill: #172033; }
    """
    return "\n".join([
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by benchmarks/comparative/harness/generate_readme_charts.py. -->",
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" '
        f'height="{height}" viewBox="0 0 {width} {height}" role="img" '
        f'aria-labelledby="title desc">',
        tag("title", {"id": "title"}, title),
        tag("desc", {"id": "desc"}, desc),
        tag("style", {}, style),
        rect(0, 0, width, height, fill=PAPER),
        *body,
        "</svg>",
        "",
    ])


def load_results(run_dir: Path) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    for path in sorted(run_dir.glob("*.json")):
        if path.name == "env.json":
            continue
        doc = json.loads(path.read_text())
        items = doc if isinstance(doc, list) else [doc]
        results.extend(item for item in items if isinstance(item, dict))
    return results


def find_one(results: list[dict[str, Any]], system: str,
             **criteria: Any) -> dict[str, Any]:
    matches = [
        row for row in results
        if row.get("system") == system
        and all(row.get(key) == value for key, value in criteria.items())
    ]
    if len(matches) != 1:
        raise ValueError(f"expected one {system} result for {criteria}, got "
                         f"{len(matches)}")
    return matches[0]


def format_latency(ns: int | float) -> str:
    if ns < 1_000:
        return f"{ns:.0f} ns"
    if ns < 1_000_000:
        return f"{ns / 1_000:.1f} us"
    return f"{ns / 1_000_000:.1f} ms"


def format_mps(messages_per_s: int | float) -> str:
    return f"{messages_per_s / 1_000_000:.1f}M"


def chart_tail_latency(results: list[dict[str, Any]], out_dir: Path) -> None:
    criteria = {
        "semantic_group": "volatile_ipc",
        "durability_mode": "none",
        "load_model": "open_loop",
        "message_bytes": 256,
        "offered_rate_mps": 1_000_000,
    }
    revoq = find_one(results, "revoq", **criteria)["latency_ns"]
    aeron = find_one(results, "aeron-ipc", **criteria)["latency_ns"]
    chronicle = find_one(
        results,
        "chronicle-queue",
        semantic_group="journal_replayable",
        durability_mode="page_cache",
        load_model="open_loop",
        message_bytes=256,
        offered_rate_mps=1_000_000,
    )["latency_ns"]
    metrics = [("p50", "p50"), ("p99", "p99"), ("p99.9", "p99_9"),
               ("max", "max")]

    width, height = 900, 440
    left, top, right, bottom = 88, 116, 42, 332
    plot_w = width - left - right
    plot_h = bottom - top
    min_y, max_y = 80.0, 1_000_000.0

    def y_pos(value: float) -> float:
        scale = ((math.log10(value) - math.log10(min_y)) /
                 (math.log10(max_y) - math.log10(min_y)))
        return bottom - scale * plot_h

    body: list[str] = [
        text(32, 40, "Tail latency: median tied, tail tighter",
             **{"class": "title"}),
        text(32, 64, "256 B payload, 1M msg/s open-loop; durability note below",
             **{"class": "subtitle"}),
    ]

    legend_y = 86
    body += [
        rect(32, legend_y - 10, 16, 16, rx=4, fill=REVOQ),
        text(56, legend_y + 3, "revoq", **{"class": "legend"}),
        rect(126, legend_y - 10, 16, 16, rx=4, fill=AERON),
        text(150, legend_y + 3, "Aeron IPC", **{"class": "legend"}),
        rect(252, legend_y - 10, 16, 16, rx=4, fill=CHRONICLE),
        text(276, legend_y + 3, "Chronicle Queue", **{"class": "legend"}),
    ]

    for tick in [100, 1_000, 10_000, 100_000, 1_000_000]:
        y = y_pos(tick)
        body.append(line(left, y, width - right, y, stroke=GRID,
                         **{"stroke-width": 1}))
        body.append(text(left - 12, y + 4, format_latency(tick),
                         **{"class": "axis", "text-anchor": "end"}))

    body += [
        line(left, top, left, bottom, stroke="#94a3b8", **{"stroke-width": 1}),
        line(left, bottom, width - right, bottom, stroke="#94a3b8",
             **{"stroke-width": 1}),
        text(24, 236, "Latency, log scale", **{"class": "axis",
                                              "transform": "rotate(-90 24 236)",
                                              "text-anchor": "middle"}),
    ]

    group_w = plot_w / len(metrics)
    bar_w = 26
    gap = 10
    series = [(revoq, REVOQ), (aeron, AERON), (chronicle, CHRONICLE)]
    series_w = len(series) * bar_w + (len(series) - 1) * gap
    for i, (label, key) in enumerate(metrics):
        center = left + group_w * i + group_w / 2
        for j, (latency, color) in enumerate(series):
            value = latency[key]
            x = center - series_w / 2 + j * (bar_w + gap)
            y = y_pos(value)
            body.append(rect(x, y, bar_w, bottom - y, rx=5, fill=color))
            body.append(text(x + bar_w / 2, y - 8, format_latency(value),
                             **{"class": "value", "text-anchor": "middle"}))
        body.append(text(center, bottom + 28, label, **{"class": "label",
                                                        "text-anchor": "middle"}))

    body.append(text(36, height - 42,
                     "Note: Chronicle Queue is journal_replayable/page_cache; "
                     "revoq and Aeron IPC are volatile_ipc/none.",
                     **{"class": "small"}))
    body.append(text(width - 36, height - 24,
                     "Source: results/2026-07-08-manual-all/*.json",
                     **{"class": "small", "text-anchor": "end"}))

    out = out_dir / "comparative-tail-latency.svg"
    out.write_text(svg_doc(
        width, height,
        "Tail latency comparison for revoq, Aeron IPC, and Chronicle Queue",
        "A log-scale bar chart showing revoq, Aeron IPC, and Chronicle Queue "
        "latency for the 256 byte, 1M messages per second point, with a note "
        "that Chronicle Queue is a separate page_cache durability cell.",
        body,
    ))


def chart_throughput(results: list[dict[str, Any]], out_dir: Path) -> None:
    payloads = [32, 64, 256, 1024]
    rows = []
    for payload in payloads:
        criteria = {
            "semantic_group": "volatile_ipc",
            "durability_mode": "none",
            "load_model": "unpaced",
            "message_bytes": payload,
            "offered_rate_mps": None,
        }
        r = find_one(results, "revoq", **criteria)["achieved_rate_mps"]
        a = find_one(results, "aeron-ipc", **criteria)["achieved_rate_mps"]
        c = find_one(
            results,
            "chronicle-queue",
            semantic_group="journal_replayable",
            durability_mode="page_cache",
            load_model="unpaced",
            message_bytes=payload,
            offered_rate_mps=None,
        )["achieved_rate_mps"]
        rows.append((payload, r, a, c))

    width, height = 900, 430
    left, top, right, bottom = 82, 116, 38, 330
    plot_w = width - left - right
    plot_h = bottom - top
    y_max = 50.0

    def y_pos(mps: float) -> float:
        return bottom - (mps / y_max) * plot_h

    body: list[str] = [
        text(32, 40, "Saturation throughput", **{"class": "title"}),
        text(32, 64, "Unpaced by payload size; durability note below",
             **{"class": "subtitle"}),
        rect(32, 72, 16, 16, rx=4, fill=REVOQ),
        text(56, 85, "revoq", **{"class": "legend"}),
        rect(126, 72, 16, 16, rx=4, fill=AERON),
        text(150, 85, "Aeron IPC", **{"class": "legend"}),
        rect(252, 72, 16, 16, rx=4, fill=CHRONICLE),
        text(276, 85, "Chronicle Queue", **{"class": "legend"}),
    ]

    for tick in [0, 10, 20, 30, 40, 50]:
        y = y_pos(tick)
        body.append(line(left, y, width - right, y, stroke=GRID,
                         **{"stroke-width": 1}))
        body.append(text(left - 12, y + 4, str(tick),
                         **{"class": "axis", "text-anchor": "end"}))

    body += [
        line(left, top, left, bottom, stroke="#94a3b8", **{"stroke-width": 1}),
        line(left, bottom, width - right, bottom, stroke="#94a3b8",
             **{"stroke-width": 1}),
        text(24, 224, "M msg/s", **{"class": "axis",
                                    "transform": "rotate(-90 24 224)",
                                    "text-anchor": "middle"}),
    ]

    group_w = plot_w / len(rows)
    bar_w = 34
    gap = 10
    for i, (payload, revoq_mps, aeron_mps, chronicle_mps) in enumerate(rows):
        center = left + group_w * i + group_w / 2
        values = [(revoq_mps, REVOQ), (aeron_mps, AERON),
                  (chronicle_mps, CHRONICLE)]
        series_w = len(values) * bar_w + (len(values) - 1) * gap
        for j, (value, color) in enumerate(values):
            mps = value / 1_000_000
            x = center - series_w / 2 + j * (bar_w + gap)
            y = y_pos(mps)
            body.append(rect(x, y, bar_w, bottom - y, rx=5, fill=color))
            body.append(text(x + bar_w / 2, y - 8, format_mps(value),
                             **{"class": "value", "text-anchor": "middle"}))
        ratio = revoq_mps / aeron_mps
        label = "parity" if 0.9 <= ratio <= 1.1 else f"{ratio:.2f}x"
        body.append(text(center, top - 12, label, **{"class": "value",
                                                     "text-anchor": "middle"}))
        body.append(text(center, bottom + 28, f"{payload} B",
                         **{"class": "label", "text-anchor": "middle"}))

    body.append(text(36, height - 42,
                     "Note: Chronicle Queue is journal_replayable/page_cache; "
                     "speedup labels compare revoq to Aeron IPC.",
                     **{"class": "small"}))
    body.append(text(width - 36, height - 24,
                     "Source: results/2026-07-08-manual-all/*.json",
                     **{"class": "small", "text-anchor": "end"}))

    out = out_dir / "comparative-throughput.svg"
    out.write_text(svg_doc(
        width, height,
        "Saturation throughput comparison for revoq, Aeron IPC, and Chronicle Queue",
        "Grouped bars show revoq, Aeron IPC, and Chronicle Queue throughput by "
        "payload size, with a note that Chronicle Queue is a separate page_cache "
        "durability cell.",
        body,
    ))


def chart_footprint(out_dir: Path) -> None:
    width, height = 900, 400
    body: list[str] = [
        text(32, 40, "Lower Hardware Resource Demand",
             **{"class": "title"}),
        text(32, 64, "Fewer runtime layers and moving parts in the tuned path",
             **{"class": "subtitle"}),
    ]

    lane_x, lane_w = 32, 836
    lane_h = 78
    lanes = [
        {
            "name": "revoq",
            "color": REVOQ,
            "y": 92,
            "blocks": [
                ("No broker", 184, 112),
                ("No JVM", 312, 94),
                ("4 pinned roles", 422, 126),
            ],
            "band": None,
            "chip_fill": "#ecfdf5",
        },
        {
            "name": "Aeron IPC",
            "color": AERON,
            "y": 196,
            "blocks": [
                ("producer JVM", 184, 118),
                ("consumer JVM", 318, 124),
            ],
            "band": ("3 busy-spin thread broker", 184, 258),
        },
        {
            "name": "Chronicle Queue",
            "color": CHRONICLE,
            "y": 300,
            "blocks": [
                ("producer", 184, 92),
                ("consumer", 292, 92),
            ],
            "band": ("managed runtime layer", 184, 200),
        },
    ]

    for lane in lanes:
        y = lane["y"]
        color = lane["color"]
        body.append(rect(lane_x, y, lane_w, lane_h, rx=10, fill=PANEL,
                         stroke=GRID))
        body.append(text(56, y + 44, lane["name"], **{"class": "label",
                                                       "font-weight": 700}))

        if lane["band"]:
            label, x, w = lane["band"]
            body.append(rect(x, y + 56, w, 16, rx=8, fill="#fff7ed",
                             stroke=color, **{"stroke-width": 1}))
            body.append(text(x + w / 2, y + 68, label,
                             **{"class": "small", "text-anchor": "middle",
                                "font-weight": 700}))

        for label, x, w in lane["blocks"]:
            fill = lane.get("chip_fill", "#ffffff")
            body.append(rect(x, y + 22, w, 34, rx=7, fill=fill,
                             stroke=color, **{"stroke-width": 2}))
            body.append(text(x + w / 2, y + 44, label,
                             **{"class": "small", "text-anchor": "middle",
                                "font-weight": 700}))

    out = out_dir / "comparative-runtime-footprint.svg"
    out.write_text(svg_doc(
        width, height,
        "Lower hardware resource demand",
        "A topology summary showing revoq as a native process tree without a "
        "broker or managed runtime, compared with Aeron IPC and Chronicle Queue.",
        body,
    ))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-dir", type=Path, default=DEFAULT_RUN_DIR)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    run_dir = args.run_dir if args.run_dir.is_absolute() else ROOT / args.run_dir
    out_dir = args.out_dir if args.out_dir.is_absolute() else ROOT / args.out_dir
    if not run_dir.is_dir():
        raise SystemExit(f"run dir not found: {run_dir}")
    out_dir.mkdir(parents=True, exist_ok=True)

    results = load_results(run_dir)
    chart_tail_latency(results, out_dir)
    chart_throughput(results, out_dir)
    chart_footprint(out_dir)
    print(f"wrote charts to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
